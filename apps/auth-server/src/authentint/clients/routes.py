"""
/admin/clients (ADR §9 "Admin") — B4. Behind `svc:admin.users`.

Redirect URIs are compared EXACTLY at /authorize (ADR §10), so what is registered here must be
exact too: absolute, no wildcard, no fragment (RFC 6749 §3.1.2). A confidential client's secret is
generated by the server, shown ONCE in the POST answer, and stored as an Argon2 hash (ADR §8).
"""

import secrets

from typing import Annotated
from typing import Literal
from urllib.parse import urlsplit
from uuid import UUID

from fastapi import APIRouter
from fastapi import Depends
from fastapi import HTTPException
from fastapi import Response
from pydantic import AfterValidator
from pydantic import BaseModel
from pydantic import ConfigDict
from pydantic import Field
from sqlalchemy import delete
from sqlalchemy import exists
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from authentint.audit import audit
from authentint.clients import queries as clients
from authentint.domain.errors import GRANT_TYPES
from authentint.infra.database import get_session
from authentint.infra.models.oauth import ClientType
from authentint.infra.models.oauth import OAuthAuthorizationCodes
from authentint.infra.models.oauth import OAuthClients
from authentint.infra.models.oauth import OAuthConsents
from authentint.infra.models.oauth import OAuthInteractions
from authentint.infra.models.oauth import OAuthRefreshTokens
from authentint.security.bearer import require_scope
from authentint.security.passwords import hash_password


router = APIRouter()

admin_users = require_scope("svc:admin.users")


def exact_uri(uri: str) -> str:
    """RFC 6749 §3.1.2: absolute, no fragment. https, or http on localhost only (RFC 8252 §7.3). No wildcard."""

    parts = urlsplit(uri)
    local = parts.hostname in ("localhost", "127.0.0.1", "::1")
    if parts.scheme not in ("https", "http") or (parts.scheme == "http" and not local) or not parts.hostname:
        raise ValueError("must be an absolute https URL")
    if parts.fragment or "#" in uri or "*" in uri:
        raise ValueError("no fragment, no wildcard: redirect URIs are compared exactly")
    return uri

RedirectUri = Annotated[str, Field(max_length=2048), AfterValidator(exact_uri)]
Grant = Literal[GRANT_TYPES]
Scope = Annotated[str, Field(pattern=r"^[a-z_:.]{1,64}$")]


class ClientView(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: str
    name: str
    type: ClientType
    redirect_uris: list[str]
    post_logout_redirect_uris: list[str]
    allowed_grants: list[str]
    allowed_scopes: list[str]
    require_consent: bool

class ClientCreated(ClientView):
    client_secret: str | None = Field(description="Confidential clients only. Shown this once: only its hash is stored")

class ClientCreate(BaseModel):
    id: str = Field(pattern=r"^[a-z0-9][a-z0-9-]{1,63}$")
    name: str = Field(min_length=1, max_length=128)
    type: ClientType
    redirect_uris: list[RedirectUri] = Field(min_length=1, max_length=20)
    post_logout_redirect_uris: list[RedirectUri] = Field(default_factory=list, max_length=20)
    allowed_grants: list[Grant] = Field(min_length=1)
    allowed_scopes: list[Scope] = Field(min_length=1, max_length=50)  # domain/scopes.grant() still intersects with the role
    require_consent: bool = True

class ClientPatch(BaseModel):
    """id and type are not editable: a public client turned confidential would need a secret it never received."""

    name: str | None = Field(None, min_length=1, max_length=128)
    redirect_uris: list[RedirectUri] | None = Field(None, min_length=1, max_length=20)
    post_logout_redirect_uris: list[RedirectUri] | None = Field(None, max_length=20)
    allowed_grants: list[Grant] | None = Field(None, min_length=1)
    allowed_scopes: list[Scope] | None = Field(None, min_length=1, max_length=50)
    require_consent: bool | None = None


async def target(session: AsyncSession, client_id: str) -> OAuthClients:
    client = await clients.get(session, client_id)

    if client is None:
        raise HTTPException(404, "unknown_client")

    return client

async def admin_audit(session: AsyncSession, event_type: str, claims: dict, client_id: str, **detail) -> None:
    await audit.emit(session, event_type, actor=UUID(claims["sub"]), outcome="success",
                     detail={"target_client_id": client_id, **detail}, client_id=client_id)


@router.get("/admin/clients", response_model=list[ClientView], tags=["admin"])
async def list_clients(claims: dict = Depends(admin_users), session: AsyncSession = Depends(get_session)):
    return (await session.scalars(select(OAuthClients).order_by(OAuthClients.id))).all()

@router.get("/admin/clients/{client_id}", response_model=ClientView, tags=["admin"], responses={404: {"description": "Unknown client"}})
async def get_client(client_id: str, claims: dict = Depends(admin_users), session: AsyncSession = Depends(get_session)):
    return await target(session, client_id)

@router.post("/admin/clients", response_model=ClientCreated, status_code=201, tags=["admin"], responses={409: {"description": "id already taken"}})
async def create_client(body: ClientCreate, claims: dict = Depends(admin_users), session: AsyncSession = Depends(get_session)):
    if await clients.get(session, body.id) is not None:
        raise HTTPException(409, "client_exists")

    secret = secrets.token_urlsafe(32) if body.type == ClientType.confidential else None
    client = OAuthClients(**body.model_dump(), secret_hash=await hash_password(secret) if secret else None)
    session.add(client)
    await admin_audit(session, "admin.client.created", claims, client.id)
    await session.commit()

    return ClientCreated(**ClientView.model_validate(client).model_dump(), client_secret=secret)

@router.patch("/admin/clients/{client_id}", response_model=ClientView, tags=["admin"], responses={404: {"description": "Unknown client"}})
async def update_client(client_id: str, body: ClientPatch, claims: dict = Depends(admin_users), session: AsyncSession = Depends(get_session)):
    client = await target(session, client_id)
    changes = body.model_dump(exclude_none=True)

    for field, value in changes.items():
        setattr(client, field, value)
    await admin_audit(session, "admin.client.updated", claims, client.id, fields=sorted(changes))
    await session.commit()

    return client

@router.delete("/admin/clients/{client_id}", status_code=204, tags=["admin"], responses={
    404: {"description": "Unknown client"},
    409: {"description": "Refresh tokens were issued to it: restrict it (PATCH) instead"},
})
async def delete_client(client_id: str, claims: dict = Depends(admin_users), session: AsyncSession = Depends(get_session)):
    """
    Only a client that never got a refresh token: one that did has users and a token history worth keeping.
    Its short-lived state (pending interactions, codes) and consents go with it.
    """

    client = await target(session, client_id)

    if await session.scalar(select(exists().where(OAuthRefreshTokens.client_id == client.id))):
        raise HTTPException(409, "client_in_use")

    for table in (OAuthInteractions, OAuthAuthorizationCodes, OAuthConsents):
        await session.execute(delete(table).where(table.client_id == client.id))
    await session.delete(client)
    await admin_audit(session, "admin.client.deleted", claims, client.id)
    await session.commit()

    return Response(status_code=204)
